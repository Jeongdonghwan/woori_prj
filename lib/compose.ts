const nearCache = new Map<string, string[]>();
function nearNames(P: Place): string[] {
  const k = P.key;
  if (!nearCache.has(k)) {
    const kinds = P.kind === '시군' || P.kind === '시군구' ? ['생활권', '시군구'] : P.kind === '생활권' ? ['생활권', '동읍면'] : ['동읍면'];
    const names = Array.from(new Set(ALL_PAGES.filter((x) => x.city === P.city && x.place !== k && kinds.includes(PLACES[x.place].kind)).map((x) => PLACES[x.place].name)));
    nearCache.set(k, names);
  }
  return nearCache.get(k)!;
}

